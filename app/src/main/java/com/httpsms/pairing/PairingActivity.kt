package com.httpsms.pairing

import android.os.Bundle
import android.text.InputType
import android.view.View
import android.widget.Button
import android.widget.EditText
import android.widget.LinearLayout
import android.widget.ProgressBar
import android.widget.TextView
import androidx.activity.ComponentActivity
import androidx.lifecycle.lifecycleScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext

/**
 * One-time pairing screen. Add this Activity to the manifest and launch it
 * when SecureStorageManager.isPaired is false or after a 401/revocation.
 */
class PairingActivity : ComponentActivity() {
    private lateinit var relayUrlInput: EditText
    private lateinit var pairingCodeInput: EditText
    private lateinit var deviceKeyInput: EditText
    private lateinit var labelInput: EditText
    private lateinit var pairButton: Button
    private lateinit var progress: ProgressBar
    private lateinit var status: TextView

    private lateinit var storage: SecureStorageManager
    private lateinit var api: RelayApiClient

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        storage = SecureStorageManager(this)
        api = RelayApiClient(storage)
        setContentView(buildContentView())

        relayUrlInput.setText(intent.getStringExtra(EXTRA_RELAY_URL).orEmpty())
        labelInput.setText(intent.getStringExtra(EXTRA_DEVICE_LABEL).orEmpty())
        pairButton.setOnClickListener { submitPairing() }
    }

    private fun buildContentView(): View {
        val margin = (24 * resources.displayMetrics.density).toInt()
        fun field(hint: String, type: Int): EditText = EditText(this).apply {
            this.hint = hint
            inputType = type
            isSingleLine = true
            setPadding(margin / 2, margin / 2, margin / 2, margin / 2)
        }

        return LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            setPadding(margin, margin, margin, margin)

            addView(TextView(context).apply {
                text = "Pair Android bridge"
                textSize = 24f
                setPadding(0, 0, 0, margin / 2)
            })
            addView(TextView(context).apply {
                text = "Use a one-time code generated by the relay administrator. The device key is stored in Android Keystore-backed storage."
                setPadding(0, 0, 0, margin)
            })

            relayUrlInput = field("Relay HTTPS URL, e.g. https://relay.example.com", InputType.TYPE_CLASS_TEXT or InputType.TYPE_TEXT_VARIATION_URI)
            pairingCodeInput = field("One-time pairing code", InputType.TYPE_CLASS_TEXT or InputType.TYPE_TEXT_FLAG_CAP_CHARACTERS)
            deviceKeyInput = field("Device key", InputType.TYPE_CLASS_TEXT or InputType.TYPE_TEXT_VARIATION_VISIBLE_PASSWORD)
            labelInput = field("Device label (optional)", InputType.TYPE_CLASS_TEXT or InputType.TYPE_TEXT_VARIATION_NORMAL)

            addView(relayUrlInput)
            addView(pairingCodeInput)
            addView(deviceKeyInput)
            addView(labelInput)

            pairButton = Button(context).apply { text = "Pair device" }
            addView(pairButton)

            progress = ProgressBar(context).apply { visibility = View.GONE }
            addView(progress)

            status = TextView(context).apply { setPadding(0, margin / 2, 0, 0) }
            addView(status)
        }
    }

    private fun submitPairing() {
        val relayUrl = relayUrlInput.text.toString().trim().trimEnd('/')
        val code = pairingCodeInput.text.toString().trim().uppercase()
        val deviceKey = deviceKeyInput.text.toString().trim()

        when {
            !relayUrl.startsWith("https://") -> return showError("Use an HTTPS relay URL.")
            relayUrl.contains("?") -> return showError("The relay URL must not contain a query string.")
            code.length !in 6..128 -> return showError("Enter the pairing code exactly as shown.")
            deviceKey.length < 20 -> return showError("The device key appears incomplete.")
        }

        setBusy(true)
        lifecycleScope.launch {
            try {
                val activated = withContext(Dispatchers.IO) {
                    api.activatePairing(relayUrl, code, deviceKey)
                }
                status.text = "Paired as ${activated.label ?: labelInput.text.toString().ifBlank { "Android bridge" }}."
                setResult(RESULT_OK)
                finish()
            } catch (error: RelayApiClient.RelayApiException) {
                showError(
                    when (error.statusCode) {
                        401 -> "Pairing failed: the code or device key is invalid, expired, or already used."
                        404 -> "This relay does not expose the pairing endpoint. Update the relay first."
                        else -> "Pairing failed: ${error.message}"
                    }
                )
            } catch (error: Exception) {
                showError("Could not reach the relay. Check the URL and network connection.")
            } finally {
                setBusy(false)
            }
        }
    }

    private fun setBusy(busy: Boolean) {
        pairButton.isEnabled = !busy
        relayUrlInput.isEnabled = !busy
        pairingCodeInput.isEnabled = !busy
        deviceKeyInput.isEnabled = !busy
        labelInput.isEnabled = !busy
        progress.visibility = if (busy) View.VISIBLE else View.GONE
        if (busy) status.text = "Pairing securely…"
    }

    private fun showError(message: String) {
        status.text = message
    }

    companion object {
        const val EXTRA_RELAY_URL = "relay_url"
        const val EXTRA_DEVICE_LABEL = "device_label"
    }
}
