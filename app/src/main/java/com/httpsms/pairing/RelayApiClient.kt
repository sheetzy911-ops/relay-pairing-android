package com.httpsms.pairing

import com.httpsms.pairing.BuildConfig
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import java.io.IOException
import java.util.concurrent.TimeUnit

@Serializable
data class PairingActivationRequest(
    @SerialName("pairing_code") val pairingCode: String,
    @SerialName("device_key") val deviceKey: String
)

@Serializable
data class PairingActivationResponse(
    @SerialName("device_id") val deviceId: String,
    @SerialName("device_key") val deviceKey: String,
    val label: String? = null
)

@Serializable
data class RelayError(val error: String? = null)

class RelayApiClient(
    private val storage: SecureStorageManager,
    private val httpClient: OkHttpClient = defaultHttpClient()
) {
    private val json = Json { ignoreUnknownKeys = true; encodeDefaults = true }
    private val contentType = "application/json; charset=utf-8".toMediaType()

    /**
     * Activates a one-time pairing. The relay requires the code and device key
     * generated by POST /auth/pairings. This method saves credentials only after
     * a successful 2xx response and validates the HTTPS origin first.
     */
    @Throws(IOException::class, RelayApiException::class)
    fun activatePairing(
        relayUrl: String,
        pairingCode: String,
        deviceKey: String
    ): PairingActivationResponse {
        val baseUrl = validateRelayUrl(relayUrl)
        val cleanCode = pairingCode.trim().uppercase()
        val cleanKey = deviceKey.trim()
        require(cleanCode.length in 6..128) { "Invalid pairing code." }
        require(cleanKey.length >= 20) { "Invalid device key." }

        val payload = json.encodeToString(
            PairingActivationRequest.serializer(),
            PairingActivationRequest(cleanCode, cleanKey)
        )
        val request = Request.Builder()
            .url("$baseUrl/v1/pairing/activate")
            .post(payload.toRequestBody(contentType))
            .header("Accept", "application/json")
            .header("X-Client-Version", BuildConfig.VERSION_NAME)
            .build()

        httpClient.newCall(request).execute().use { response ->
            val body = response.body?.string().orEmpty()
            if (!response.isSuccessful) {
                throw RelayApiException(response.code, parseError(body))
            }
            val activated = runCatching {
                json.decodeFromString(PairingActivationResponse.serializer(), body)
            }.getOrElse { throw RelayApiException(response.code, "Malformed activation response") }

            if (activated.deviceId.isBlank() || activated.deviceKey.isBlank()) {
                throw RelayApiException(response.code, "Activation response did not contain device credentials")
            }
            if (activated.deviceKey != cleanKey) {
                throw RelayApiException(response.code, "Activation response key mismatch")
            }

            storage.savePairing(baseUrl, activated.deviceId, activated.deviceKey)
            return activated
        }
    }

    /** Creates a request authenticated with the paired device key. */
    fun authenticatedRequest(path: String): Request {
        val baseUrl = storage.authenticatedRelayUrl()
        require(path.startsWith("/")) { "Relay path must start with /." }
        return Request.Builder()
            .url("$baseUrl$path")
            .header("Accept", "application/json")
            .header("X-Device-Key", storage.authenticatedDeviceKey())
            .header("X-Client-Version", BuildConfig.VERSION_NAME)
            .build()
    }

    /**
     * Call this when any authenticated bridge request receives HTTP 401.
     * A revoked key must not be retried indefinitely.
     */
    fun handleAuthenticationFailure(httpStatus: Int) {
        if (httpStatus == 401) storage.clearPairing()
    }

    private fun parseError(body: String): String {
        return runCatching { json.decodeFromString(RelayError.serializer(), body).error }
            .getOrNull()
            ?.takeIf { it.isNotBlank() }
            ?: "Relay rejected the request"
    }

    private fun validateRelayUrl(value: String): String {
        val normalized = value.trim().trimEnd('/')
        require(normalized.startsWith("https://")) { "The relay must use HTTPS." }
        require(!normalized.contains("?")) { "Relay URL must not contain a query string." }
        return normalized
    }

    class RelayApiException(val statusCode: Int, override val message: String) : IOException(message)

    companion object {
        fun defaultHttpClient(): OkHttpClient = OkHttpClient.Builder()
            .connectTimeout(10, TimeUnit.SECONDS)
            .readTimeout(15, TimeUnit.SECONDS)
            .writeTimeout(15, TimeUnit.SECONDS)
            .callTimeout(30, TimeUnit.SECONDS)
            .retryOnConnectionFailure(true)
            .build()
    }
}
